/* ============================================================
   DIRECT HTML REPORT
   ============================================================ */

function renderDirectHtmlReport(
    caseId,
    html
) {

    const container =
        document.getElementById(
            "report-content"
        );


    if (!container) {
        return;
    }


    container.innerHTML = `

        <section class="ldd-report-viewer">

            <header class="ldd-report-header">

                <div class="ldd-report-heading">

                    <span class="eyebrow">
                        FORENSIC REPORT
                    </span>

                    <h2>
                        Investigation Report
                    </h2>

                    <p>
                        Generated forensic case report.
                    </p>

                </div>


                <div class="ldd-report-actions">

                    <button
                        type="button"
                        class="button secondary"
                        id="ldd-report-open"
                    >
                        Open Report
                    </button>

                </div>

            </header>


            <div class="ldd-report-document">

                <iframe
                    id="ldd-report-frame"
                    title="Linux Digital Detective Forensic Report"
                    sandbox="allow-same-origin"
                ></iframe>

            </div>

        </section>

    `;


    const frame =
        document.getElementById(
            "ldd-report-frame"
        );


    if (frame) {

        frame.srcdoc =
            html;

    }


    const openButton =
        document.getElementById(
            "ldd-report-open"
        );


    if (openButton) {

        openButton.addEventListener(
            "click",
            () => {

                const newWindow =
                    window.open(
                        "",
                        "_blank"
                    );


                if (!newWindow) {

                    return;

                }


                newWindow.document.open();

                newWindow.document.write(
                    html
                );

                newWindow.document.close();

            }
        );

    }
}


/* ============================================================
   ACTIONS
   ============================================================ */

function bindReportActions(
    caseId
) {

    const openButton =
        document.getElementById(
            "ldd-report-open"
        );


    if (!openButton) {
        return;
    }


    openButton.addEventListener(
        "click",
        () => {

            /*
             * Open the backend-generated report
             * directly in a new browser tab.
             */

            const reportUrl =
                `/api/cases/${encodeURIComponent(
                    caseId
                )}/report`;


            window.open(
                reportUrl,
                "_blank",
                "noopener,noreferrer"
            );

        }
    );
}


/* ============================================================
   STAGE FORMAT
   ============================================================ */

function formatReportStage(
    stage
) {

    return String(
        stage ||
        "UNKNOWN"
    )
        .replaceAll(
            "_",
            " "
        )
        .replace(
            /\b\w/g,
            (
                character
            ) =>
                character.toUpperCase()
        );
}


/* ============================================================
   CASE SELECTION
   ============================================================ */

document.addEventListener(
    "ldd:case-selected",
    (
        event
    ) => {

        const caseId =
            event.detail?.caseId;


        if (!caseId) {
            return;
        }


        setTimeout(
            () => {

                if (
                    LDD.currentCase ===
                    caseId
                ) {

                    loadReport(
                        caseId
                    );

                }

            },
            50
        );

    }
);
