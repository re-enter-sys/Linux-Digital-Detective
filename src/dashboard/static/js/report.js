        Array.isArray(
            investigation.mitre
        )
            ? investigation.mitre
            : [];


    const risk =
        investigation.risk_score ||
        {};


    const story =
        investigation.attack_story ||
        {};


    const severity =
        risk.severity ||
        story.highest_finding_severity ||
        "INFO";


    const confidence =
        Number(
            risk.confidence ||
            story.confidence ||
            0
        );


